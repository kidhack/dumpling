#!/usr/bin/env python3
"""Verifies icons.txt against the SF Symbols catalog and writes ListSymbols.swift."""
import json, os, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
catalog = "/System/Library/CoreServices/CoreGlyphs.bundle/Contents/Resources/name_availability.plist"
syms = json.loads(subprocess.run(["plutil", "-convert", "json", "-o", "-", catalog], capture_output=True).stdout)["symbols"]

sections, seen, problems = [], set(), []
for line in open(os.path.join(here, "icons.txt")):
    line = line.strip()
    if not line or line.startswith("# "):
        continue
    if line.startswith("## "):
        sections.append((line[3:], []))
        continue
    name, words = (p.strip() for p in line.split(":", 1))
    if name in seen:
        problems.append(f"duplicate: {name}")
    elif name not in syms:
        problems.append(f"missing: {name}")
    elif str(syms[name]) > "2024":
        problems.append(f"too new: {name} ({syms[name]})")
    else:
        seen.add(name)
        sections[-1][1].append((name, words))

total = sum(len(s[1]) for s in sections)
print(f"{total} icons in {len(sections)} sections", file=sys.stderr)
for p in problems:
    print(p, file=sys.stderr)

out = ['// Generated by ios/Tools/ListIcons/generate.py from icons.txt. Edit icons.txt, not this file.',
       '', 'enum ListSymbols {', '    static let defaultSymbol = "list.bullet"', '',
       '    struct Section: Identifiable {', '        let title: String', '        let symbols: [Symbol]',
       '        var id: String { title }', '    }', '',
       '    struct Symbol: Hashable {', '        let name: String', '        /// Plain words people search with.',
       '        let keywords: String', '    }', '',
       f'    /// {total} icons, all verified against the SF Symbols catalog.', '    static let sections: [Section] = [']
for title, items in sections:
    out.append(f'        Section(title: "{title}", symbols: [')
    for name, words in items:
        out.append(f'            Symbol(name: "{name}", keywords: "{words}"),')
    out.append('        ]),')
out += ['    ]', '}', '']
open(os.path.join(here, "../../DumplingApp/Views/ListSymbols.swift"), "w").write("\n".join(out))
